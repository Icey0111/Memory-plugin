import assert from 'node:assert/strict';
import { calibrateSimilarityThreshold, compareRetrievalRuns, evaluateRankedCases, scoreRankedCase } from './retrieval-eval.js';
const one = scoreRankedCase({ expected: ['b'], ranked: ['a', 'b', 'c'], k: 3 });
assert.equal(one.recall, 1); assert.equal(one.reciprocal_rank, 0.5);
const result = evaluateRankedCases([{ expected:['b'], ranked:['a','b'] }, { expected:['x'], ranked:['x','y'] }], { k: 2 });
assert.equal(result.hit_rate, 1); assert.ok(result.mrr > 0.7);
const calibration = calibrateSimilarityThreshold([{score:0.91,label:true},{score:0.84,label:true},{score:0.78,label:true},{score:0.74,label:false},{score:0.63,label:false}], { minRecall:1 });
assert.equal(calibration.met_min_recall, true); assert.equal(calibration.confusion.fn, 0);
const comparison = compareRetrievalRuns({ recall_at_k:0.8 }, { recall_at_k:0.9 });
assert.ok(comparison.delta.recall_at_k > 0);
console.log('retrieval-eval tests passed');
